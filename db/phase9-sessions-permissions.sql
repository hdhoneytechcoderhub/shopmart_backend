-- ddl-auto=update creates/alters these automatically; this file is for reference / manual setup.

-- 1) Session management: refresh_tokens gains device/IP/last-used tracking
ALTER TABLE refresh_tokens ADD COLUMN IF NOT EXISTS device_info VARCHAR(255);
ALTER TABLE refresh_tokens ADD COLUMN IF NOT EXISTS ip_address  VARCHAR(64);
ALTER TABLE refresh_tokens ADD COLUMN IF NOT EXISTS last_used_at TIMESTAMPTZ;

-- 2) Permission matrix
CREATE TABLE IF NOT EXISTS permission_groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    CONSTRAINT uk_permission_group_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(100) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    module      VARCHAR(100),
    screen_key  VARCHAR(100),
    group_id    BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    CONSTRAINT uk_permission_code UNIQUE (code),
    CONSTRAINT fk_permission_group FOREIGN KEY (group_id) REFERENCES permission_groups (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS custom_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    CONSTRAINT uk_custom_role_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS custom_role_permissions (
    custom_role_id BIGINT NOT NULL REFERENCES custom_roles (id) ON DELETE CASCADE,
    permission_id  BIGINT NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    PRIMARY KEY (custom_role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS user_custom_roles (
    user_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    custom_role_id BIGINT NOT NULL REFERENCES custom_roles (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, custom_role_id)
);

