-- Promotes db/phase8-superadmin-attendance.sql into the actual Flyway pipeline.
-- That file was never more than a loose reference script sitting outside
-- src/main/resources/db/migration — Flyway never ran it automatically, so any
-- database that didn't have it applied by hand is missing this table
-- entirely, which is what GET /attendance/all and /attendance/report were
-- 500ing on (Hibernate's ddl-auto=validate would only have caught this at
-- startup if it validates every entity as strictly as expected — either way,
-- this closes the gap for good rather than relying on it having been run manually).

CREATE TABLE IF NOT EXISTS attendance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    login_time  TIMESTAMPTZ NOT NULL,
    logout_time TIMESTAMPTZ,
    total_hours DOUBLE PRECISION,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_attendance_user ON attendance (user_id);

-- Defensive: if an earlier partial/ad-hoc version of this table exists
-- without one of these columns, add it rather than assume.
ALTER TABLE attendance ADD COLUMN IF NOT EXISTS total_hours DOUBLE PRECISION;
ALTER TABLE attendance ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE attendance ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
