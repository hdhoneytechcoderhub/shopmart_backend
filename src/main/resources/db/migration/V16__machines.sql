-- The Machine entity (com.shopmart.module.machine.entity.Machine) has no
-- backing migration anywhere in this codebase — not in src/main/resources/db/migration,
-- and not even as a loose reference script under db/ (unlike attendance,
-- which at least had db/phase8-superadmin-attendance.sql). A fresh database
-- is missing this table entirely, which is what GET /machines was 500ing on.

CREATE TABLE IF NOT EXISTS machines (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    model_number VARCHAR(255),
    brand        VARCHAR(255),
    description  VARCHAR(2000),
    is_deleted   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_machines_deleted ON machines (is_deleted);

-- @ElementCollection List<String> images on Machine.
CREATE TABLE IF NOT EXISTS machine_images (
    machine_id BIGINT NOT NULL REFERENCES machines (id) ON DELETE CASCADE,
    image_url  VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_machine_images_machine ON machine_images (machine_id);

